// The text in the chosen language (the same text when there is nothing for it).
inline std::string Tr(const std::string& s)
{
    if (!lang || s.empty()) return s;
    if (lang == 2)
    {
        const auto& table = Italian();
        const auto found = table.find(s);
        if (found != table.end()) return found->second;
    }
    else
    {
        const auto& t = Spanish();
        const auto it = t.find(s);
        if (it != t.end()) return it->second;
    }
    for (const auto& p : lang == 2 ? ItalianPrefixes() : SpanishPrefixes())
        if (s.size() > p.first.size() && !s.compare(0, p.first.size(), p.first)) return p.second + s.substr(p.first.size());
    return s;
}
