#!/usr/bin/env python3
"""Emits gen/apps_table.cpp: the per-frame "exec" function of every named game
application (bag, party menu, battle, ...), found through the OverlayManagerTemplate
symbols in the NEF. The frontend uses it to tell which application is running.

usage: apps.py <build dir> <out dir>
       apps.py --layout <layout file> <out dir>   (from tools/make_layout.py, no build needed)
"""
import collections
import io
import os
import re
import struct
import sys


class WriteIfChanged(io.StringIO):
    """A text file that is only written if its new contents differ, so that a rebuild
    does not recompile what did not change."""
    def __init__(self, path):
        super().__init__()
        self.path = path

    def __exit__(self, *exc):
        text = self.getvalue()
        try:
            old = open(self.path).read()
        except OSError:
            old = None
        if old != text:
            with open(self.path, 'w', newline='\n') as f:
                f.write(text)
        return super().__exit__(*exc)




def write_table(out_dir, rows, found):
    with WriteIfChanged(os.path.join(out_dir, 'apps_table.cpp')) as f:
        f.write('// Generated by tools/apps.py. Do not edit.\n#include "recomp_api.h"\n\n')
        f.write('const RcApp rc_apps[] = {\n')
        for app, sec, addr, *phases in rows:
            # Also the functions that start and end it (0: none of its own), see below.
            init, init_sec, exit_, exit_sec = phases if phases else (0, '', 0, '')
            f.write(f'    {{"{app}", "{sec}", 0x{addr:08X}u, 0x{init:08X}u, "{init_sec}", 0x{exit_:08X}u, "{exit_sec}"}},\n')
        f.write('};\n')
        f.write(f'const unsigned rc_num_apps = {len(rows)};\n\n')
        # Functions the frontend watches to decide which screen matters (tools/focus_symbols.txt).
        f.write('const RcApp rc_focus_syms[] = {\n')
        for name, sec, addr in found:
            f.write(f'    {{"{name}", "{sec}", 0x{addr:08X}u}},\n')
        f.write('    {nullptr, nullptr, 0},\n};\n')
        f.write(f'const unsigned rc_num_focus_syms = {len(found)};\n')


if sys.argv[1] == '--layout':
    import json
    layout = json.load(open(sys.argv[2]))
    out_dir = sys.argv[3]
    os.makedirs(out_dir, exist_ok=True)
    write_table(out_dir, [tuple(r) for r in layout['apps']], [tuple(r) for r in layout['focus']])
    # The function list is only used by --trace-funcs, a development option.
    with WriteIfChanged(os.path.join(out_dir, 'symbols.txt')) as f:
        pass
    print(len(layout['apps']), 'applications')
    sys.exit(0)

from elftools.elf.elffile import ELFFile

build_dir, out_dir = sys.argv[1], sys.argv[2]
nef = [f for f in os.listdir(build_dir) if f.endswith('.nef')][0]

NAME = re.compile(r'^(?:g|s)(?:OverlayTemplate|Application|App)_(\w+?)(?:\$\d+)?$')
SKIP = {'main_defs', 'main_table', 'DTCM', 'ITCM'}

with open(os.path.join(build_dir, nef), 'rb') as f:
    elf = ELFFile(f)
    secs = [(s.name, s['sh_addr']) for s in elf.iter_sections()]
# Overlay ids follow the order in which overlay sections first appear.
overlays = []
bases = {}
for name, addr in secs:
    if name and name not in bases:
        bases[name] = addr
    if name and not name.startswith('.') and not name.startswith('binary') and name != 'main' \
            and name not in SKIP and name not in overlays:
        overlays.append(name)

# The linker map lists static symbols too, which the NEF's symbol table does not.
templates = []
functions = []   # (section, address, size, name) of every function
current = None
line_re = re.compile(r'^\s+([0-9A-Fa-f]{8}) ([0-9A-Fa-f]{8}) (\S+)\s+(\S+)')
with open(os.path.join(build_dir, nef + '.xMAP'), errors='replace') as f:
    for line in f:
        if line.startswith('# .'):
            current = line[3:].strip()
            continue
        m = line_re.match(line)
        if not m or current not in bases:
            continue
        addr, size, kind, name = int(m.group(1), 16), int(m.group(2), 16), m.group(3), m.group(4)
        if kind in ('.text', '.itcm') and size and not name.startswith(('.', '$', '@')):
            functions.append((current, addr & ~1, size, re.sub(r'\$\d+$', '', name)))
        n = NAME.match(name)
        if n:
            templates.append((n.group(1), current, bases[current], addr))

with WriteIfChanged(os.path.join(out_dir, 'symbols.txt')) as f:
    for sec, addr, size, name in functions:
        f.write(f'{sec} {addr:08X} {size:X} {name}\n')

main_end = 0x02000000 + os.path.getsize(os.path.join(build_dir, 'main.sbin'))

images = {}
def image(name):
    if name not in images:
        images[name] = open(os.path.join(build_dir, name + '.sbin'), 'rb').read()
    return images[name]

rows = []
for app, sec_name, sec_base, addr in sorted(set(templates)):
    if any(r[0] == app for r in rows):
        continue
    data = image(sec_name)
    off = addr - sec_base
    if off < 0 or off + 16 > len(data):
        continue
    init, exec_fn, exit_fn, ovy = struct.unpack_from('<4I', data, off)
    if exec_fn < 0x01FF8000 or exec_fn >= 0x02400000:
        continue
    if exec_fn < main_end:
        code_sec = 'main'
    elif ovy == 0xFFFFFFFF:
        # No overlay of its own: the code is in the overlay holding the template.
        code_sec = sec_name
    elif ovy < len(overlays):
        code_sec = overlays[ovy]
    else:
        continue
    def where(fn):
        # The section of a start or end function: the main module, or the overlay of the
        # application (where its per-frame function is too).
        fn &= ~1
        if 0x02000000 <= fn < main_end:
            return 'main'
        return code_sec if code_sec != 'main' else None
    rows.append([app, code_sec, exec_fn & ~1, init & ~1, where(init), exit_fn & ~1, where(exit_fn)])

# An application runs its start function every frame until it is ready and its end
# function until it has cleaned up, so the frontend can keep its layout through the
# fades at both ends. A start or end function that several applications share (by
# section and address) cannot tell them apart and is left out.
uses = collections.Counter()
for r in rows:
    uses[(r[4], r[3])] += 1
    uses[(r[6], r[5])] += 1
for r in rows:
    for i in (3, 5):
        if r[i + 1] is None or uses[(r[i + 1], r[i])] > 1:
            r[i], r[i + 1] = 0, ''
rows = [(r[0], r[1], r[2], r[3], r[4], r[5], r[6]) for r in rows]

# Functions the frontend watches to decide which screen matters (tools/focus_symbols.txt).
wanted = [l.split()[0] for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'focus_symbols.txt'))
          if l.strip() and not l.startswith('#')]
found = []
for name in wanted:
    hits = [fn for fn in functions if fn[3] == name]
    if not hits:
        print('warning: focus symbol not found:', name, file=sys.stderr)
    for sec, addr, size, _ in hits:
        found.append((name, sec, addr))
write_table(out_dir, rows, found)
print(len(rows), 'applications')
print(len(functions), 'functions in symbols.txt')
